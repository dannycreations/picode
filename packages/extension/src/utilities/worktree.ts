import { execFile } from 'node:child_process';
import { cp, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { promisify } from 'node:util';

import { logger } from '@pi-code/shared/core/logger';

const execFileAsync = promisify(execFile);

const GIT_TIMEOUT_MS = 120_000;
const GIT_MAX_BUFFER = 64 * 1024 * 1024;

export interface IsolatedWorktree {
  readonly path: string;
  readonly baseRoot: string;
  readonly baseCommit: string;
}

let worktreeQueue: Promise<void> = Promise.resolve();

export function withWorktreeLock<T>(fn: () => Promise<T>): Promise<T> {
  const run = worktreeQueue.then(fn, fn);
  worktreeQueue = run.then(
    () => undefined,
    () => undefined,
  );
  return run;
}

async function runGit(cwd: string, args: readonly string[]): Promise<string> {
  const { stdout } = await execFileAsync('git', [...args], {
    cwd,
    encoding: 'utf-8',
    maxBuffer: GIT_MAX_BUFFER,
    timeout: GIT_TIMEOUT_MS,
    env: {
      ...process.env,
      GIT_AUTHOR_NAME: 'Pi Code',
      GIT_AUTHOR_EMAIL: 'pi-code@local',
      GIT_COMMITTER_NAME: 'Pi Code',
      GIT_COMMITTER_EMAIL: 'pi-code@local',
    },
  });
  return stdout;
}

export async function getGitRoot(cwd: string): Promise<string | null> {
  try {
    const root = await runGit(cwd, ['rev-parse', '--show-toplevel']);
    const trimmed = root.trim();
    return trimmed.length > 0 ? trimmed : null;
  } catch {
    return null;
  }
}

async function removeWorktreeDirectory(worktree: IsolatedWorktree): Promise<void> {
  try {
    await runGit(worktree.baseRoot, ['worktree', 'remove', '--force', worktree.path]);
  } catch (err) {
    logger.warn('Could not remove git worktree cleanly; deleting the directory directly.', err);
  }
  await rm(worktree.path, { recursive: true, force: true }).catch((err) => logger.warn('Could not delete worktree directory:', err));
  try {
    await runGit(worktree.baseRoot, ['worktree', 'prune']);
  } catch {
    // Best effort only.
  }
}

export async function createIsolatedWorktree(baseCwd: string): Promise<IsolatedWorktree | null> {
  const baseRoot = await getGitRoot(baseCwd);
  if (!baseRoot) return null;

  const worktreePath = await mkdtemp(join(tmpdir(), 'pi-code-worktree-'));

  try {
    await runGit(baseRoot, ['worktree', 'add', '--detach', worktreePath, 'HEAD']);

    // Carry the parent's uncommitted tracked changes into the isolated copy so
    // the agent starts from the same state the user is looking at.
    let trackedDiff = '';
    try {
      trackedDiff = await runGit(baseRoot, ['diff', '--binary', 'HEAD']);
    } catch (err) {
      logger.warn('Could not read uncommitted tracked changes; the isolated copy may start from HEAD.', err);
    }
    if (trackedDiff.trim().length > 0) {
      const basePatchPath = join(tmpdir(), `pi-code-base-${Date.now()}-${Math.random().toString(36).slice(2)}.patch`);
      await writeFile(basePatchPath, trackedDiff, 'utf8');
      try {
        await runGit(worktreePath, ['apply', '--3way', basePatchPath]);
      } finally {
        await rm(basePatchPath, { force: true }).catch(() => undefined);
      }
    }

    // Untracked files are not in HEAD, so copy them explicitly. Ignored files
    // stay out; build artifacts can be regenerated by the agent's commands.
    const untrackedOutput = await runGit(baseRoot, ['ls-files', '--others', '--exclude-standard']).catch(() => '');
    for (const relativePath of untrackedOutput
      .split('\n')
      .map((line) => line.trim())
      .filter(Boolean)) {
      const source = join(baseRoot, relativePath);
      const target = join(worktreePath, relativePath);
      await cp(source, target, { recursive: true, force: true }).catch((err) =>
        logger.warn(`Could not copy untracked file ${relativePath} into the worktree:`, err),
      );
    }

    // Freeze the starting state as a commit so later diffs contain only the
    // agent's changes, including any commits the agent itself makes.
    await runGit(worktreePath, ['add', '-A']);
    await runGit(worktreePath, ['commit', '--allow-empty', '--no-verify', '--no-gpg-sign', '-m', 'pi-code: isolated base']);
    const baseCommit = (await runGit(worktreePath, ['rev-parse', 'HEAD'])).trim();

    return { path: worktreePath, baseRoot, baseCommit };
  } catch (err) {
    logger.error('Failed to create an isolated worktree; falling back to the shared workspace.', err);
    await rm(worktreePath, { recursive: true, force: true }).catch(() => undefined);
    try {
      await runGit(baseRoot, ['worktree', 'prune']);
    } catch {
      // Best effort only.
    }
    return null;
  }
}

export async function integrateIsolatedWorktree(worktree: IsolatedWorktree): Promise<{ ok: true } | { ok: false; reason: string }> {
  let diff = '';
  try {
    // Stage everything, including files the agent created but never added, so the
    // diff below captures the complete change set rather than only tracked edits.
    await runGit(worktree.path, ['add', '-A']);
    diff = await runGit(worktree.path, ['diff', '--cached', '--binary', worktree.baseCommit]);
  } catch (err) {
    return { ok: false, reason: `Could not read the worktree diff: ${String(err)}` };
  }

  if (diff.trim().length === 0) {
    await removeWorktreeDirectory(worktree);
    return { ok: true };
  }

  const patchPath = join(tmpdir(), `pi-code-${Date.now()}-${Math.random().toString(36).slice(2)}.patch`);
  try {
    await writeFile(patchPath, diff, 'utf8');
    // Validate before mutating the base tree so a conflicting patch does not
    // leave conflict markers or a partially applied working tree behind.
    await runGit(worktree.baseRoot, ['apply', '--check', '--3way', patchPath]);
    await runGit(worktree.baseRoot, ['apply', '--3way', patchPath]);
    await removeWorktreeDirectory(worktree);
    await rm(patchPath, { force: true }).catch(() => undefined);
    return { ok: true };
  } catch (err) {
    const reason = `Could not apply the isolated changes back to the workspace: ${String(err)}. The changes remain in ${worktree.path} and the patch is at ${patchPath}.`;
    logger.error(reason);
    return { ok: false, reason };
  }
}

export async function discardIsolatedWorktree(worktree: IsolatedWorktree): Promise<void> {
  await removeWorktreeDirectory(worktree);
  try {
    await runGit(worktree.baseRoot, ['worktree', 'prune']);
  } catch {
    // Best effort only.
  }
}
